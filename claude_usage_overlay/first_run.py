"""첫 실행 판정.

**안내창은 없앴다.** 그 창은 "트레이 아이콘을 작업 표시줄로 꺼내 두면 편하다"고
알려주는 것이 목적이었고, 그 전제는 *프로그램이 아이콘을 꺼낼 수 없다*는 것이었다.
그 전제가 틀렸다 — 설정의 "작업 표시줄에 트레이 아이콘 고정"은 **즉시 반영되고**,
첫 실행에는 __main__이 그것을 자동으로 켜준다. 사용자가 할 일이 없으므로 알릴
것도 없다.

설계 문서(스펙 2.8절)와 예전 tray_promote 주석이 "즉시 반영되지 않는다 · 다음
로그온부터"라고 적어둔 실측은 **재현되지 않았다.** 그 실측이 어떻게 나왔는지는
확인하지 못했지만, 실제 사용 경로(사용자가 직접 띄운 인스턴스, 재부팅 뒤 자동
실행)에서는 예외 없이 즉시 반영된다.

**첫 실행 판정은 남는다.** 자동 고정을 딱 한 번만 하기 위해서다 — 매 기동마다
켜면 나중에 직접 숨긴 사람과 싸우게 된다.
"""

from pathlib import Path

from .config import config_path


def is_first_run(path: Path | None = None) -> bool:
    """config.json이 없으면 첫 실행이다.

    깨진 파일도 "한 번 켠 적이 있다"는 증거로 본다. 내용을 읽어 판정하면 오타 하나에
    자동 고정이 매 기동마다 되살아난다.
    """
    return not (path or config_path()).exists()
